'use client'
import {
  arrow as arrowMiddleware,
  FloatingArrow,
  FloatingFocusManager,
  FloatingPortal,
  offset,
  size,
  useMergeRefs,
} from '@floating-ui/react'
import type { Middleware, Placement } from '@floating-ui/react'
import { cn } from '@ultraviolet/utils'
import { forwardRef, useId, useLayoutEffect, useRef } from 'react'
import type { CSSProperties, ReactNode, RefObject } from 'react'
import { VisuallyHidden } from '../../../Other/VisuallyHidden'
import { usePopupContext } from './context'
import type { PopupRole } from './context'
import { popupV2Style } from './styles.css'

type PopupPanelProps = {
  children: ReactNode
  /**
   * ARIA role of the popup element. Also drives `aria-haspopup` on the trigger.
   * @default 'dialog'
   */
  role?: PopupRole
  /**
   * Popup placement. Flipped automatically when there is not enough space.
   * @default 'bottom-start'
   */
  placement?: Placement
  /**
   * Where the popup is portaled. Pass `null` to render inline.
   * @default the closest `dialog` parent, or document.body
   */
  portalTarget?: HTMLElement | null
  /**
   * When `true`, keeps the popup width synced to the trigger width.
   * @default false
   */
  matchTriggerWidth?: boolean
  /**
   * Background color applied to the panel and its arrow.
   * @default 'neutral'
   */
  sentiment?: 'neutral' | 'primary'
  /**
   * When `true`, renders an arrow pointing at the trigger.
   * @default false
   */
  arrow?: boolean
  /**
   * When `true`, traps Tab focus inside the popup.
   * @default false
   */
  focusTrap?: boolean
  /**
   * Which element to focus when the Popup opens. Can be either a number (tabbable index as specified by the order) or a ref.
   * Set the value to -1 to keep the focus on the Trigger element.
   */
  initialFocus?: number | RefObject<HTMLElement | null>
  /**
   * Restore focus to the trigger when the popup closes. Available even
   * without `focusTrap`. Set to `false` to disable all focus management.
   * @default true
   */
  returnFocus?: boolean
  /**
   * id of the popup element. Auto-generated by the Root if not provided.
   */
  id?: string
  /**
   * id of an element that labels the popup.
   */
  'aria-labelledby'?: string
  /**
   * Accessible name of the popup, rendered in a `VisuallyHidden` element and
   * wired through `aria-labelledby`.
   */
  accessibleLabel?: string
  className?: string
  style?: CSSProperties
  'data-testid'?: string
}

/**
 * Popup content container: portals, positions and manages focus, and applies
 * the role and ARIA attributes.
 */
export const Panel = forwardRef<HTMLDivElement, PopupPanelProps>(
  (
    {
      children,
      role = 'dialog',
      placement = 'bottom-start',
      portalTarget: userPortalTarget,
      matchTriggerWidth = false,
      sentiment = 'neutral',
      arrow = false,
      focusTrap = false,
      initialFocus,
      returnFocus = true,
      id,
      'aria-labelledby': ariaLabelledby,
      accessibleLabel,
      className,
      style,
      'data-testid': dataTestId,
    },
    forwardedRef,
  ) => {
    const {
      context,
      floatingStyles,
      getFloatingProps,
      id: contextId,
      isMounted,
      placement: resolvedPlacement,
      refs,
      setPanelMiddleware,
      setPlacement,
      setRole,
      status,
    } = usePopupContext()

    const arrowRef = useRef<SVGSVGElement>(null)
    const panelRef = useMergeRefs([refs.setFloating, forwardedRef])
    const panelId = id ?? contextId
    const labelId = useId()

    useLayoutEffect(() => {
      setPlacement(placement)
    }, [placement, setPlacement])

    useLayoutEffect(() => {
      setRole(role)
    }, [role, setRole])

    useLayoutEffect(() => {
      const middleware: Middleware[] = []
      if (matchTriggerWidth) {
        middleware.push(
          size({
            apply: ({ rects, elements }) => {
              Object.assign(elements.floating.style, {
                minWidth: `${rects.reference.width}px`,
              })
            },
          }),
        )
      }
      if (arrow) {
        middleware.push(offset(4), arrowMiddleware({ element: arrowRef, padding: 4 }))
      }
      setPanelMiddleware(middleware)
    }, [matchTriggerWidth, arrow, arrowRef, setPanelMiddleware])

    if (!isMounted) {
      return null
    }

    const hasInitialFocus = initialFocus !== undefined
    const manageFocus = focusTrap || returnFocus || hasInitialFocus

    // portal the Popup to the parent dialog so that clicks inside the Popup don't close the dialog
    const parentDialogElement = (refs.reference.current as HTMLElement)?.closest('dialog')
    const defaultPortalTarget = typeof window === 'undefined' ? null : parentDialogElement || document.body
    const portalTarget = userPortalTarget ?? defaultPortalTarget

    const popupElement = (
      <div
        ref={panelRef}
        {...getFloatingProps()}
        data-placement={resolvedPlacement}
        data-testid={dataTestId}
        id={panelId}
        role={role}
        aria-labelledby={ariaLabelledby ?? (accessibleLabel ? labelId : undefined)}
        className={cn(
          popupV2Style.panel,
          popupV2Style.panelSentiment[sentiment],
          status === 'open' || status === 'close' ? popupV2Style.animation[status] : null,
          className,
        )}
        style={{ ...floatingStyles, ...style }}
      >
        {arrow ? (
          <FloatingArrow
            className={popupV2Style.arrowSentiment[sentiment]}
            context={context}
            ref={arrowRef}
            tipRadius={2}
          />
        ) : null}

        {accessibleLabel ? <VisuallyHidden id={labelId}>{accessibleLabel}</VisuallyHidden> : null}
        {children}
      </div>
    )

    return (
      <FloatingPortal root={portalTarget}>
        {manageFocus ? (
          <FloatingFocusManager
            context={context}
            initialFocus={initialFocus}
            modal={focusTrap}
            returnFocus={returnFocus}
          >
            {popupElement}
          </FloatingFocusManager>
        ) : (
          popupElement
        )}
      </FloatingPortal>
    )
  },
)

Panel.displayName = 'Popup.Panel'
