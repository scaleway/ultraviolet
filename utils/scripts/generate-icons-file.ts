const wrapSvg = (svgContent: string) => {
  const hasMultipleElements = svgContent.trim().split(/<path|<rect|<circle|<line|<ellipse|<g/u).length > 2

  return hasMultipleElements ? `<>${svgContent}</>` : svgContent
}

const COMMENT_HEADER = `
  'use client'

  /**
* Provide the icon component for the icon name.
* This file is automatically generated from /utils/scripts/generate-icons-file.tsx.
* PLEASE DO NOT EDIT HERE
*/`

const templateIcon = (iconName: string, svg: string, svgSmall?: string, svgDisabled?: string) => {
  const deprecated = DEPRECATED_ICONS.find(icon => icon.name === iconName)

  return `${COMMENT_HEADER}
  import { Icon } from '../Icon'
  import type { IconProps } from '../Icon'

  ${
    deprecated
      ? `
  /**
    * @deprecated ${deprecated.deprecatedReason}
    */`
      : ''
  }
  ${
    svgSmall
      ? `export const ${iconName} = (props: Omit<IconProps, 'children'>) => (
      <Icon {...props}>{typeof props.size === 'string' && ['medium', 'large', 'xlarge', 'xxlarge'].includes(props.size) ? ${wrapSvg(svg)} : ${wrapSvg(svgSmall)}}</Icon>
  )`
      : `export const ${iconName} = (props: Omit<IconProps, 'children'>) => (
      <Icon {...props}>${svgDisabled ? `{props.disabled ? ${wrapSvg(svgDisabled)} : ${wrapSvg(svg)}}` : svg}</Icon>
  )`
  }

  ${iconName}.displayName = '${iconName}'
`
}

const templateFlag = (iconName: string, svg: string, svgDisabled?: string) => {
  const deprecated = DEPRECATED_ICONS.find(icon => icon.name === iconName)

  return `${COMMENT_HEADER}
  import { Icon } from '../Icon'
  import type { IconProps } from '../Icon'

  ${
    deprecated
      ? `
  /**
    * @deprecated ${deprecated.deprecatedReason}
    */`
      : ''
  }
 export const ${iconName} = ({
    disabled,
    ...props
  }: Omit<IconProps, 'children'>) =><Icon {...props}>{disabled ? ${wrapSvg(svgDisabled ?? svg)} : ${wrapSvg(svg)}}</Icon>

  ${iconName}.displayName = '${iconName}'
`
}
const templateLogo = (logoName: string, svg: string, svgDark?: string) => {
  const deprecated = DEPRECATED_ICONS.find(icon => icon.name === logoName)

  return `${COMMENT_HEADER}
  import { Icon } from '../Icon'
  import type { IconProps } from '../Icon'
${svgDark ? `import { useResolvedTheme } from '@ultraviolet/themes'` : ''}
  ${
    deprecated
      ? `
  /**
    * @deprecated ${deprecated.deprecatedReason}
    */`
      : ''
  }
 export const ${logoName} = (props: Omit<IconProps, 'children'>) => ${
   svgDark
     ? `{
  const theme = useResolvedTheme()  
  const isLight = theme === "light"

  return (
      <Icon {...props}>{isLight ? <>${svg}</> : <>${svgDark}</>}</Icon>
  )}`
     : `(<Icon {...props}>${svg}</Icon>)`
 }

  ${logoName}.displayName = '${logoName}'
`
}

const toPascalCase = (str: string) => str.replaceAll(/(^\w|-\w)/gv, match => match.replace('-', '').toUpperCase())

const generateVariableName = (filePath: string) => {
  const parsedPath = path.parse(filePath)
  const fileName = toPascalCase(parsedPath.name)
  const parentDir = path.basename(path.dirname(filePath))

  const isOutline = parentDir.includes('outline')
  const iconName = `${fileName}${isOutline ? 'Outline' : ''}`

  return iconName
}

const readDirectoryRecursive = async (dir: string) => {
  const list = await promises.readdir(dir, { withFileTypes: true })

  const results = await Promise.all(
    list.map(async file => {
      const filePath = path.resolve(dir, file.name)

      if (file.isDirectory()) {
        return readDirectoryRecursive(filePath)
      }
      if (path.extname(file.name).toLowerCase() === '.svg') {
        return [filePath]
      }
      return []
    }),
  )

  return results.flat()
}

const readSvg = async (filePath: string, suffix: string) => {
  const svgContent = await promises.readFile(filePath, 'utf8')
  const innerSvgContent = svgContent.replaceAll(/<svg[^>]*>|<\/svg>/gv, '') // Remove <svg ...> and </svg> tags

  // Replace class with className
  const updatedSvgContent = innerSvgContent
    .replaceAll('class=', 'className=')
    .replaceAll('fill-rule=', 'fillRule=')
    .replaceAll('fill-opacity=', 'fillOpacity=')
    .replaceAll('clip-rule=', 'clipRule=')
    .replaceAll('clip-path=', 'clipPath=')
    .replaceAll('stop-color=', 'stopColor=')
    .replaceAll('flood-opacity=', 'floodOpacity=')
    .replaceAll('stroke-width=', 'strokeWidth=')
    .replaceAll('stroke-linecap=', 'strokeLinecap=')
    .replaceAll('stroke-linejoin=', 'strokeLinejoin=')
    .replaceAll('stop-opacity=', 'stopOpacity=')
    .replaceAll('color-interpolation-filters=', 'colorInterpolationFilters=')
    .replaceAll('xlink:href=', 'xlinkHref=')
    .replaceAll('`', '\\`')

  if (['ProductIcon', 'CategoryIcon'].includes(suffix)) {
    const svgWithClassNames = updatedSvgContent.replaceAll(/className="[^"]*"/gv, '')

    const colorToClass: Record<string, string> = filePath.includes(`${path.sep}original${path.sep}`)
      ? {
          '#521094': 'fillWeak',
          '#BF95F9': 'fillStrong',
          '#FFFFFF': 'fill',
          '#FFF': 'fill',
        }
      : {
          '#F1EEFC': 'fillWeak',
          '#A060F6': 'fillStrong',
          '#521094': 'fill',
        }

    return svgWithClassNames.replaceAll(/fill="([^"]*)"/gv, (match: string, color: string) => {
      const className = colorToClass[color.toUpperCase()]
      if (className) {
        return `${match} className="${className}"`
      }
      if (!['NONE', '#FFF'].includes(color.toUpperCase())) {
        console.error(`Unrecognized fill color "${color}" in file: ${filePath}`)
      }
      return match
    })
  }

  if (suffix === 'Icon') {
    return updatedSvgContent.replaceAll(/fill="[^"]*"/gv, '')
  }

  return updatedSvgContent
}

const getDisabledFile = (file: string) => {
  const disabledFileName = file.replace('default', 'disabled')
  return existsSync(disabledFileName) ? disabledFileName : file
}

const getSmallFile = (file: string) => {
  const smallFileName = file.replace('default', 'small')

  return existsSync(smallFileName) ? smallFileName : file
}

const getDarkFile = (file: string) => {
  const darkFileName = file.replace('light', 'dark')

  return existsSync(darkFileName) ? darkFileName : file
}

const generateContent = (
  type: string,
  generatedName: string,
  svg: { default: string; dark?: string; small?: string; smallDisabled?: string; disabled?: string },
) => {
  if (type === 'Logo') {
    return templateLogo(generatedName, svg.default, svg.dark)
  }

  if (type === 'Flags') {
    return templateFlag(generatedName, svg.default, svg.disabled)
  }

  return templateIcon(generatedName, svg.default, svg.small, svg.disabled)
}

const resetIconsFolder = async (folderPath: string) => {
  try {
    const files = await promises.readdir(folderPath)
    const deletePromises = files.map(async file => promises.unlink(path.join(folderPath, file)))
    await Promise.all(deletePromises)
    console.log(`Deleted all files in ${folderPath}`)
  } catch (error) {
    console.error('Error deleting files in icons folder:', error)
  }
}

const main = async () => {
  await Promise.all(
    COMPONENTS.map(async component => {
      console.log(`Generating ${component.name}...`)
      await resetIconsFolder(component.output) // we clean the folder before generating the new icons

      const iconNames: string[] = []

      try {
        const files = await readDirectoryRecursive(component.input)
        const generatedIcons = await Promise.all(
          files
            .filter(
              file =>
                !file.includes('small') &&
                !file.includes('disabled') &&
                !(file.includes('/dark/') && component.name === 'Logo'),
            )
            .map(async file => {
              const generatedName = `${generateVariableName(file)}${component.suffix}`
              const smallFile = getSmallFile(file)
              const disabledFile = getDisabledFile(file)
              const darkFile = getDarkFile(file)

              const svgContent = await readSvg(file, component.suffix)
              const svgContentSmall = smallFile === file ? undefined : await readSvg(smallFile, component.suffix)
              const svgContentDisabled =
                component.name === 'Flags' && disabledFile !== file
                  ? await readSvg(disabledFile, component.suffix)
                  : undefined
              const svgContentDark =
                component.name === 'Logo' && darkFile !== file ? await readSvg(darkFile, component.suffix) : undefined

              return {
                generatedName,
                content: generateContent(component.name, generatedName, {
                  default: svgContent,
                  small: svgContentSmall,
                  disabled: svgContentDisabled,
                  dark: svgContentDark,
                }),
              }
            }),
        )

        iconNames.push(...generatedIcons.map(({ generatedName }) => generatedName))

        await Promise.all(
          generatedIcons.map(({ generatedName, content }) =>
            promises.writeFile(`${component.output}/${generatedName}.tsx`, content),
          ),
        )

        const exports = generatedIcons
          .map(({ generatedName }) => `export { ${generatedName} } from './${generatedName}'\n`)
          .join('')
        await promises.appendFile(
          `${component.output}/index.ts`,
          `${COMMENT_HEADER}\n${exports}export type ${component.typeName} = ${iconNames.map(name => `"${name}"`).join(' | ')}\n`,
        )
      } catch (error) {
        console.error('Error reading directory:', error)
      }
    }),
  )
}

await main()
